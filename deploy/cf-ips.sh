#!/bin/bash
# Refresh the edge IP ranges this host trusts, into the nftables sets and nginx's real-IP config:
#   cloudflare_v4/v6     https://www.cloudflare.com/ips-v4 + ips-v6  -> port 443 and nginx real-IP
#   github_actions_v4    api.github.com/meta ".actions" (v4)         -> port 2222, the CI deploy path
# Runs as root from a daily systemd timer and on setup.
#
# Every list is validated before anything is applied, and the two trust lists do not share a failure
# path: a bad Cloudflare fetch changes nothing at all, while a bad GitHub fetch keeps the last-known-good
# ranges from $ELEM (so a GitHub outage neither empties the set nor blocks the Cloudflare refresh) and
# exits non-zero at the end, so the systemd unit reports the staleness.
set -euo pipefail
ELEM=/etc/nftables.d/cloudflare.nft
V4RE='^[0-9]{1,3}(\.[0-9]{1,3}){3}/[0-9]{1,2}$'

v4=$(curl -fsS --max-time 20 https://www.cloudflare.com/ips-v4/)
v6=$(curl -fsS --max-time 20 https://www.cloudflare.com/ips-v6/)
[[ $(wc -l <<<"$v4") -ge 5 && $(wc -l <<<"$v6") -ge 3 ]] || { echo "suspicious CF list" >&2; exit 1; }

# GitHub publishes a few thousand (Azure) prefixes; v6 entries are dropped, the deploy path is IPv4.
gh_stale=""
gh4=$(curl -fsS --max-time 30 -H 'Accept: application/vnd.github+json' -H 'User-Agent: glo-people' \
  https://api.github.com/meta |
  python3 -c 'import json,sys; [print(x) for x in json.load(sys.stdin)["actions"] if ":" not in x]' || true)
g4=$(grep -cE "$V4RE" <<<"$gh4" || true)
if [[ $g4 -lt 100 || $g4 -ne $(wc -l <<<"$gh4") ]]; then
  gh_stale="fetch failed or looked wrong ($g4 valid of $(wc -l <<<"$gh4") lines); reusing $ELEM"
  gh4=$(sed -n 's/^add element inet filter github_actions_v4 { \(.*\) }$/\1/p' "$ELEM" 2>/dev/null |
        tr ',' '\n' | tr -d ' ' | grep -v '^$' || true)
  g4=$(grep -cE "$V4RE" <<<"$gh4" || true)
  [[ $g4 -ge 100 ]] || { echo "github actions ranges: $gh_stale, and no usable fallback either" >&2; exit 1; }
fi

nft flush set inet filter cloudflare_v4
nft flush set inet filter cloudflare_v6
nft flush set inet filter github_actions_v4
nft add element inet filter cloudflare_v4 "{ $(paste -sd, <<<"$v4") }"
nft add element inet filter cloudflare_v6 "{ $(paste -sd, <<<"$v6") }"
nft add element inet filter github_actions_v4 "{ $(paste -sd, <<<"$gh4") }"

# Persist for boot (included by /etc/nftables.conf)
{
  echo "add element inet filter cloudflare_v4 { $(paste -sd, <<<"$v4") }"
  echo "add element inet filter cloudflare_v6 { $(paste -sd, <<<"$v6") }"
  echo "add element inet filter github_actions_v4 { $(paste -sd, <<<"$gh4") }"
} > "$ELEM"

conf=/opt/glo-people/nginx/cloudflare-realip.conf
{ echo "# generated by cf-ips.sh $(date -u +%FT%TZ)"; sed 's/.*/set_real_ip_from &;/' <<<"$v4"$'\n'"$v6"; } > "$conf.tmp"
chmod 644 "$conf.tmp" && mv "$conf.tmp" "$conf"
docker exec glo-people-nginx-1 nginx -s reload 2>/dev/null || true

echo "ranges applied: cloudflare $(wc -l <<<"$v4") v4 + $(wc -l <<<"$v6") v6, github actions $g4 v4"
[[ -z $gh_stale ]] || { echo "WARNING github actions ranges are STALE: $gh_stale" >&2; exit 1; }
