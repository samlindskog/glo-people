#!/bin/bash
# Refresh Cloudflare IP ranges into the nftables sets and nginx's real-IP config.
# Runs as root from a weekly systemd timer and on setup.
set -euo pipefail
v4=$(curl -fsS --max-time 20 https://www.cloudflare.com/ips-v4/)
v6=$(curl -fsS --max-time 20 https://www.cloudflare.com/ips-v6/)
[[ $(wc -l <<<"$v4") -ge 5 && $(wc -l <<<"$v6") -ge 3 ]] || { echo "suspicious CF list" >&2; exit 1; }

nft flush set inet filter cloudflare_v4
nft flush set inet filter cloudflare_v6
nft add element inet filter cloudflare_v4 "{ $(paste -sd, <<<"$v4") }"
nft add element inet filter cloudflare_v6 "{ $(paste -sd, <<<"$v6") }"

# Persist for boot (included by /etc/nftables.conf)
{
  echo "add element inet filter cloudflare_v4 { $(paste -sd, <<<"$v4") }"
  echo "add element inet filter cloudflare_v6 { $(paste -sd, <<<"$v6") }"
} > /etc/nftables.d/cloudflare.nft

conf=/opt/glo-people/nginx/cloudflare-realip.conf
{ echo "# generated by cf-ips.sh $(date -u +%FT%TZ)"; sed 's/.*/set_real_ip_from &;/' <<<"$v4"$'\n'"$v6"; } > "$conf.tmp"
chmod 644 "$conf.tmp" && mv "$conf.tmp" "$conf"
docker exec glo-people-nginx-1 nginx -s reload 2>/dev/null || true
